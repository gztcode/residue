#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Residue PRD v4.3 机械校验（CR-011 · 第 9 轮 23 条阻塞）

比 verify9.py 多两件事：
1) 逐条断言第 9 轮 23 条修法已落地
2) **量的唯一性扫描** —— 机器查「同一个量在全文是否出现两套不同算法 / 判据」
   （这是「同名落点未穷举」与「一个量两说」两类错误的通用防线）
"""
import sys, re

# ── 目录重组：切到 docs/contract/，使脚本内的相对文件名继续有效 ──
import os as _os
_HERE = _os.path.dirname(_os.path.abspath(__file__))
_CONTRACT = _os.path.join(_os.path.dirname(_os.path.dirname(_HERE)), 'docs', 'contract')
if _os.path.isdir(_CONTRACT):
    _os.chdir(_CONTRACT)

P = sys.argv[1] if len(sys.argv) > 1 else 'Residue-PRD-v4.3.md'
TXT = open(P, encoding='utf-8').read()
L = TXT.split('\n')
FAIL, OK = [], []
DEAD = ['已归零', '已失效', '不另立', '不再', '原「', '已删', '以此表为准',
        '不得出现', '旧口径', '已被取代', '全文只此', 'CR-010 · R', 'CR-011 ·',
        '除本串外不出现', '旧样式串', '已被取代', '已改为引用', '改由']


def must(c, m):
    (OK if c else FAIL).append(m)


def dead_ok(s):
    bad = []
    for i, line in enumerate(L, 1):
        if s in line and not any(d in line for d in DEAD):
            bad.append('L%d' % i)
    return (not bad), ('同名落点: %r 仍出现在生效条文(%s)' % (s[:34], ','.join(bad)))


# ============ 第 1 段：第 9 轮 23 条 ============
T = {
 'A1':  ['`a` 只由本表判据产生', '不计入 `a`', '改由「指标定义表 · M4」的 L0 判据承载'],
 'A2':  ['影子期必须做 L0 判定', '每轮扫描时，产品对判定域内每条可再生物料候选执行一次 L0 判定',
         '记录位置（V4 不新增顶层字段）', '影子期内每次扫描对判定域内每条可再生物料候选至少执行一次 L0 判定'],
 'A3':  ['`a ≠ 0` **或** `b = 0`', '`b = 0` 并入既有「L0 误判」项'],
 'A4':  ['`a` 按 (来源, 应用版本) 分组、跨轮次累计'],
 'A5':  ['删去括号内的 `K = T − J` 字样'],
 'A6':  ['一天最多 +1', '有成功扫描的日历日数'],
 'A7':  ['应用版本变更时', '轮次不变', '报告产出失败的扫描**按失败扫描处理、不计入计数日**'],
 'A8':  ['取快照时刻唯一', '本轮首次成功扫描完成时刻'],
 'A9':  ['现行口径 = 「指标定义表 · M6」', '容量阈值仅计 14 日外历史'],
 'A10': ['该字段为「不适用 + 原因」时改取该行的写入时刻', '该行不参与留存计量'],
 'A11': ['新入域来源（点亮后首次命中、本轮无快照）占行', '本轮无快照 · 扫描时点值 · 非结算值'],
 'B7':  ['剩余天数该格显示 `—`'],
 'B8':  ['第 `<N>` 轮 · 观察期未满 · 待结算扫描（无需操作）', '两串均带轮次前缀'],
 'B9':  ['本条自本轮报告产出后适用', '本轮未结算'],
 'B10': ['否（观察期未满）', '否（判定域内无来源）'],
 'B11': ['本行移出「观察期未满」「误判率未达 C2 合格线」两项', '「规则更新后观察期归零」标「本期不交付」'],
 'B12': ['视为未满足门槛、计入未达标来源集合', '否（权限不足 · 未判定）'],
 'Q1':  ['删去括号内的 `K = T − J` 字样'],
 'Q2':  ['冻结时点分列', '总量 `T` 冻结于本轮快照日'],
 'Q3':  ['`a` 按 (来源, 应用版本) 分组、跨轮次累计'],
 'Q4':  ['`a ≠ 0` **或** `b = 0`'],
 'Q5':  ['视为未满足门槛、计入未达标来源集合'],
 'Q6':  ['报告产出失败的扫描**按失败扫描处理'],
 '自查1': ['① 观察期的终点 = 本轮第 14 个计数日之后的第一次成功扫描'],
}
for tag, keys in T.items():
    for k in keys:
        must(k in TXT, '%s: %s' % (tag, k[:48]))

# §8 超限行实删
must('| 超限 | 单次容量/条目数触顶。' in TXT, 'B11: §8 超限行已实删前两项')

# ============ 第 2 段：量的唯一性扫描（通用防线） ============
# 每个量只允许存在一套算法式；命中多套 = 失败
# 「唯一式」的正确判据：**式子在生效条文里只能有一处给出定义**，多处*引用*是正常的。
# 故只查「给出定义」的表述（带「= 」且在指标定义表或 AC 生效条文中），
# 而不查单纯的引用与历史说明。
UNIQ = {
 'K 的第二套算法': [r'`K = T − J`'],
 'J 的第二套算法': [r'`J = T − K − 本轮重建命中数`'],
 '计数日的次数式': [r'本轮计数日 = 本轮内成功扫描的累计次数'],
}
# 生效条文 = 不在变更清单 / 历史留痕 / 收窄理由说明中
HIST = ['变更清单', '相对 v', '为什么收窄', '证据：', '删 ', '已删', '已被取代']
for name, pats in UNIQ.items():
    live = []
    for i, line in enumerate(L, 1):
        for p in pats:
            if re.search(p, line):
                if any(h in line for h in HIST):
                    continue
                if any(d in line for d in DEAD):
                    continue
                live.append(i)
    must(len(live) == 0,
         '唯一性: %s 在生效条文出现于 L%s' % (name, live))

# H 的公式：允许多处引用，但**给出定义**的位置只允许在 M2
h_def = [i for i, line in enumerate(L, 1)
         if 'H = min(30, T)' in line and '算法（唯一式）' in line]
must(len(h_def) == 1, '唯一性: H 的定义式只在 M2 一处给出（L%s）' % h_def)

# ============ 第 3 段：同名落点穷举 ============
ZERO = [
 '观察期已满 · 待结算', '等待结算扫描成功', '本轮重建命中数', '下一轮快照重新计入',
 '该规则版本内永久', '`b` = 观测面、非门槛', '自然日数**；扫描失败',
 '观察期已满」的定义 = 已观察天数 ≥ 14 且该次扫描已产出',
 'J = T − K − 本轮重建命中数', '自然日数',
 '单次容量/条目数触顶、观察期未满、误判率未达 C2 合格线、规则更新后观察期归零',
 '本轮计数日 = 本轮内成功扫描的累计次数',
]
for z in ZERO:
    ok, msg = dead_ok(z)
    must(ok, msg)

# ============ 第 4 段：结构不变性 ============
ac = sorted(set(re.findall(r'\bAC-(\d\d)\b', TXT)))
must(ac == ['%02d' % i for i in range(1, 21)], '结构: AC 仍 20 条，实际 %d' % len(ac))
must('7 页 × 1 形态' in TXT, '结构: 7 页声明在')
must('7 类状态数不变' in TXT, '结构: 7 类状态数不变声明在')
must('本期不交付' in TXT, '结构: 不交付标记在')
must('H = min(30, T)' in TXT, '结构: 门槛公式在')
must('200 × 10⁶' in TXT, '结构: 200MB 单位在')
must('第 `<N>` 轮' in TXT, '结构: 轮次前缀样式在')
must(TXT.count('指标定义表 · M') >= 8, '结构: 指标定义表被 ≥8 处引用')

# ============ 第 5 段：指标定义表五要素 ============
for mid in ['M1', 'M2', 'M3', 'M4', 'M5', 'M6']:
    m = re.search(r'#### %s · (.+?)(?=\n#### |\Z)' % mid, TXT, re.S)
    must(m is not None, '指标定义表 %s 段存在' % mid)
    if m:
        for k in ['判据', '算法（唯一式）', '读数源', '写入时刻', '计数对象']:
            must(k in m.group(0), '指标定义表 %s: 要素「%s」' % (mid, k))

# ============ 第 6 段：算术走查 ============
must('`K + J = T`' in TXT, '算术: 恒等式在')
must('`H ≥ 1`' in TXT or 'H ≥ 1' in TXT, '算术: H≥1 在')
must('`b ≥ 1`' in TXT, '算术: b≥1 在')
must('`a` = 0' in TXT or '`a = 0`' in TXT, '算术: a=0 在')

print('=' * 60)
print('通过 %d 项' % len(OK))
if FAIL:
    print('失败 %d 项：' % len(FAIL))
    for f in FAIL:
        print('  ✗', f)
    sys.exit(1)
print('全部通过')
