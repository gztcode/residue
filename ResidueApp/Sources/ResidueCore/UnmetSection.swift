// ============================================================
// ③ 页未达项区的**唯一事实源**（封闭枚举 · 三态）（CR-036）
//
// 为什么要有这个类型：空数组无法区分三件对用户**完全不同**的事——
//   「没有未达项」/「没有可判定的东西」/「还没判定过」。
// 现状用 `unmetNotices: [SemanticSlot] = []` 承载这三者，界面只能显示
// 一句「读取中」——把「尚未知」说成「还在读」（不变量 ③：不把未知判为安全）。
//
// ⚠️ **不新增 `SemanticSlot` 的 case**（恒为 7 个）——
// 这里是**状态分派**（呈现层），不是新的槽位类型。
// ============================================================

/// ③ 页未达项区的态。
public enum UnmetSection: Sendable, Equatable {
    /// **态①**：有未达项 ⇒ 逐行列出（全局项在前、来源项在后，**一项一行**）。
    case rows([SemanticSlot])

    /// **态②**：判定域非空且**确无**未达项。
    ///
    /// ⚠️ 「无未达项」**不等于**「已达标」——开关仍不可点亮。
    case none

    /// **态③**：判定域为空 ⇒ **没有可判定的东西**（不是「判过了并且达标」）。
    case emptyDomain(EmptyDomainCause)
}

/// 空判定域的**成因**（两个成因对用户是两条不同的消息）。
public enum EmptyDomainCause: Sendable, Equatable {
    /// 一个候选都没有 ⇒ 无可扫描来源。
    case noScannableSource

    /// 有候选，但**全部在判定域外**（如 `pipx run`）⇒ 无可清理候选。
    case noCleanupCandidate
}
