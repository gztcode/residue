#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Residue PRD v4.2 机械校验（CR-010）

针对第 8 轮三方终审的 13 根因，逐根因断言「修法已落到正文」；
并对「同名落点未穷举」建立强制检查：每个被改对象，旧措辞归零 + 新措辞落点数一致。

用法：python3 verify9.py [PRD路径]
"""
import sys, re

P = sys.argv[1] if len(sys.argv) > 1 else 'Residue-PRD-v4.2.md'
TXT = open(P, encoding='utf-8').read()
L = TXT.split('\n')

FAIL = []
OK = []


def must(cond, msg):
    (OK if cond else FAIL).append(msg)


def count(s):
    return TXT.count(s)


# ================================================================
# 第 1 段：根因修法落地断言（13 条）
# ================================================================

# --- R1: J 唯一式 ---
must(count('`K + J = T`') >= 1, 'R1: 恒等式 K+J=T 仍在（应存在）')
must('J = T − K − 本轮重建命中数' not in TXT or '不另立第二套式子' in TXT,
     'R1: 旧式「J = T − K − 本轮重建命中数」已归零')
must('`K = T − J`' not in TXT or 'K = T − J**，`J` 为派生量' in TXT
     or '`K = T − J`，`J` 为派生量' in TXT, 'R1: 「K = T − J」只允许作为 M3 派生式出现')
must('唯一式' in TXT and 'M3' in TXT, 'R1: 指标定义表 M3 存在（唯一式所在）')
must(TXT.count('**`J` 为派生量**') >= 1, 'R1: J 明示为派生量')
# 关键：不得同时出现「重建命中数」作为独立量
must('本轮重建命中数' not in TXT or '不另立为独立量' in TXT
     or '不另立第二套式子' in TXT, 'R1: 「重建命中数」不再作为独立量')

# --- R2: a 有判据 ---
must('首检无活引用 → 复检有引用' in TXT or '首检无引用 → 复检有引用' in TXT
     or '首检无活引用' in TXT, 'R2: a 的唯一判据已写入')
must('M4' in TXT, 'R2: 指标定义表 M4 存在')
must('复检时刻' in TXT, 'R2: a 的写入时刻已定义')

# --- R3: b 是门槛项 ---
must('**门槛项**（组 B 要求 `b ≥ 1`）' in TXT, 'R3: b 已改为门槛项（符号表）')
must('`b` = 门槛项、须 ≥ 1' in TXT or '`b` = 门槛项' in TXT, 'R3: AC-09 ⑥ 已同步 b 为门槛项')
must('`a = 0` 且 `b ≥ 1`' in TXT, 'R3: AC-09 ⑦ 达标式已含 b ≥ 1')
must('b` = 观测面、非门槛' not in TXT or '以此表为准' in TXT,
     'R3: 旧口径「b = 观测面、非门槛」已归零')
must('M5' in TXT, 'R3: 指标定义表 M5 存在')

# --- R4: 观察期单一时钟 ---
must('本轮计数日' in TXT, 'R4: 「本轮计数日」已引入')
must('扫描失败、跳过、低电量**不计入计数日**' in TXT or '不计入计数日' in TXT,
     'R4: 失败不推进计数日的规则已写死')
must('自然日数**；扫描失败' not in TXT, 'R4: 旧口径「自然日数 + 失败不推进」已归零')
must('不存在「第 14 个自然日早已过去' in TXT, 'R4: 第 2 轮退化为 1 天的缺陷已写明并封堵')
must('M1' in TXT, 'R4: 指标定义表 M1 存在')

# --- R5: 唯一样式串 ---
must('观察期未满 · 待结算扫描（无需操作）' in TXT, 'R5: 唯一样式串已写入')
must('观察期已满 · 待结算' not in TXT or '已归零' in TXT,
     'R5: 旧样式串「观察期已满 · 待结算」已归零')
must('等待结算扫描成功' not in TXT or '已归零' in TXT,
     'R5: 旧样式串「等待结算扫描成功」已归零')
must('「已满 / 未满」的唯一定义在本表' in TXT, 'R5: 已满/未满唯一定义已锚到 M1')

# --- R6: 自动开轮可观测 ---
must('第 2 轮 · 观察期 0/14 天' in TXT, 'R6: ③ 页带轮次文案已定义')
must('上一轮：样本' in TXT, 'R6: ⑤ 页「上一轮」行已定义')
must('写入口唯一' in TXT, 'R6: 写入口唯一性已写明')
must('优先级低于本条' in TXT, 'R6: 应用版本重置与开轮的优先级已定义')
must('轮次**是唯一新增的**显示字段' in TXT or '唯一新增的**显示字段' in TXT,
     'R6: 轮次定性为显示字段（非状态类）')

# --- R7: 永久边界 ---
must('当前应用版本内永久' in TXT, 'R7: 「当前应用版本内永久」已写入')
must('该规则版本内永久' not in TXT or '已失效' in TXT or '随 AC-16 不交付而失效' in TXT,
     'R7: 旧口径「该规则版本内永久」已归零')
must('只在**应用版本变更**时清零' in TXT, 'R7: a 的重置边界已改挂应用版本')

# --- R8: 留存 ---
must('200 × 10⁶' in TXT, 'R8: 200 MB 单位已写死')
must('减数项只含执行记录' in TXT or '减数项只含「14 日内的执行记录」' in TXT,
     'R8: 减数项已收窄为执行记录')
must('日志保留 90 天，或 14 日外历史满 200 MB，先到者为准' in TXT,
     'R8: 留存口径界面落点文案已定义')
must('按记录时刻升序' in TXT, 'R8: 「最旧」排序键已写死')
must('14 日豁免只作用于容量阈值，不作用于 90 天期限' in TXT, 'R8: 豁免边界已写死')
must('M6' in TXT, 'R8: 指标定义表 M6 存在')

# --- R9: 判定域 ---
must('本轮观察期开始时的快照内命中' in TXT, 'R9: 判定域已加快照限定')

# --- R10: 失联不继承 ---
must('下一轮以新快照重算 `T`，与上轮失联条目无继承关系' in TXT, 'R10: 失联不继承已写明')
must('下一轮快照重新计入' not in TXT, 'R10: 旧句「下一轮快照重新计入」已归零')

# --- R11: 未达项 ---
must('一项一行、逐行独立' in TXT, 'R11: 「一项一行」已写明')
must('两项分行列出' in TXT, 'R11: 两项分行已写明')
must('L0 误判 1 次（检查 128 次）' in TXT, 'R11: L0 误判项文案格式已定义')
must('L0 未检查（检查 0 次）' in TXT, 'R11: b=0 的文案已定义')
must('`a` 亦只在报告产出后判定' in TXT, 'R11: 来源项判定前置已写死')
must('②′' in TXT, 'R11: 补了「仅 L0 误判」的用例②′')
must('本条**四条独立用例**' in TXT, 'R11: 用例数已改为四条')

# --- R12: 可构造 ---
must('取 `T ≤ 30` 的来源' in TXT, 'R12: 可构造口径已写入')
must('以第 ⑤ 页读数反推结论' in TXT, 'R12: 判定改为读数反推')

# --- R13: pipx 时点 ---
must('扫描时点值 · 非结算值' in TXT, 'R13: pipx 行时点标注已定义')
must('不套用 `K + J = T` 恒等式' in TXT, 'R13: pipx 行不套用恒等式已写明')

# ================================================================
# 第 2 段：结构不变性（不新增 AC / 页面 / 状态类）
# ================================================================
ac = sorted(set(re.findall(r'\bAC-(\d\d)\b', TXT)))
must(ac == [f'{i:02d}' for i in range(1, 21)], '结构: AC 编号仍为 01~20 共 20 条，实际 %d 条' % len(ac))
must(TXT.count('7 页 × 1 形态') >= 1, '结构: 7 页 × 1 形态声明仍在')
must('7 类状态' in TXT or '共 **7 类**' in TXT, '结构: 7 类状态数未变')
must('本期不交付' in TXT, '结构: 不交付标记仍在')
must('`pipx` run' in TXT, '结构: pipx 隔离口径仍在')
must('H = min(30, T)' in TXT, '结构: 门槛公式未变')
must('90 天 / 容量上限 200 MB' in TXT or '90 天 / 容量 200 MB' in TXT
     or '日志保留期 = **90 天 / 容量上限 200 MB' in TXT, '结构: 90 天 / 200 MB 未变')
must('14 日内' in TXT, '结构: 14 日口径仍在')

# ================================================================
# 第 3 段：同名落点穷举（第 10 次教训的强制检查）
#
# 关键区分：旧措辞可以出现在「已作废 / 已被取代」的说明上下文里
#（那是必要的留痕），但**不得出现在生效条文里**。
# 判据：命中处所在行必须带作废标记，否则判失败。
# ================================================================
DEAD_MARK = ['已归零', '已失效', '不另立', '不再', '原「', '已删', '以此表为准',
             '不得出现', '旧口径', '已被取代', '全文只此', 'CR-010 · R',
             '除本串外不出现', '旧样式串']

def old_wording_only_in_dead_context(s):
    """返回 (ok, msg)：旧措辞的每一处命中是否都在作废上下文中"""
    bad = []
    for i, line in enumerate(L, 1):
        if s in line:
            if not any(m in line for m in DEAD_MARK):
                bad.append('L%d' % i)
    if bad:
        return False, '同名落点: 旧措辞 %r 仍出现在生效条文（%s）' % (s[:30], ','.join(bad))
    return True, '同名落点: 旧措辞 %r 仅存于作废上下文' % s[:30]

ZERO = [
    '观察期已满 · 待结算',
    '等待结算扫描成功',
    '本轮重建命中数',
    '下一轮快照重新计入',
    '该规则版本内永久',
    '`b` = 观测面、非门槛',
    'K = T − J**，失联条目本轮不计入样本',
    '自然日数**；扫描失败',
    '观察期已满」的定义 = 已观察天数 ≥ 14 且该次扫描已产出',
    'b` = 观测面、非门槛',
    'J = T − K − 本轮重建命中数',
    '自然日数',
]
for z in ZERO:
    ok, msg = old_wording_only_in_dead_context(z)
    must(ok, msg)

# 新措辞必须**全部落点一致**：同一对象的表述不应在不同地方不同
must(TXT.count('观察期未满 · 待结算扫描（无需操作）') >= 2,
     '同名落点: 唯一样式串在 ≥2 处一致出现（定义 + 使用）')
must(TXT.count('指标定义表 · M') >= 6, '同名落点: 指标定义表被 ≥6 处引用')

# 关键：收窄声明表不得再复述旧定义（这是第 10 次的原点）
must('本表不再复述该定义' in TXT, '同名落点: 收窄声明表已改为引用 M1（不复述旧定义）')

# ================================================================
# 第 4 段：指标定义表五要素完备性
# ================================================================
for mid, keys in {
    'M1': ['判据', '算法（唯一式）', '读数源', '写入时刻', '计数对象'],
    'M2': ['判据', '算法（唯一式）', '读数源', '写入时刻', '计数对象'],
    'M3': ['判据', '算法（唯一式）', '读数源', '写入时刻', '计数对象'],
    'M4': ['判据', '写入时刻', '计数对象'],
    'M5': ['判据', '算法（唯一式）', '读数源', '写入时刻', '计数对象'],
    'M6': ['判据', '算法（唯一式）', '读数源', '写入时刻', '计数对象'],
}.items():
    # 取 M 段文本
    m = re.search(r'#### %s · (.+?)(?=\n#### |\Z)' % mid, TXT, re.S)
    if not m:
        FAIL.append('指标定义表: %s 段缺失' % mid)
        continue
    seg = m.group(0)
    for k in keys:
        must(k in seg, '指标定义表 %s: 缺要素「%s」' % (mid, k))

# ================================================================
# 第 5 段：算术走查
# ================================================================
must('H = min(30, T)' in TXT and 'H ≥ 1' in TXT, '算术: H ≥ 1 边界成立')
must('K + J = T' in TXT, '算术: 恒等式在')
must('`a` = 0' in TXT or '`a = 0`' in TXT, '算术: a=0 门槛在')
must('`b ≥ 1`' in TXT, '算术: b≥1 门槛在')

# ================================================================
print('=' * 60)
print('通过 %d 项' % len(OK))
if FAIL:
    print('失败 %d 项：' % len(FAIL))
    for f in FAIL:
        print('  ✗', f)
    sys.exit(1)
print('全部通过')
